/**
 * Build the native app's score view into ONE self-contained HTML string (M2, docs/mobile/plan.md).
 *
 *   npm run -w @turkish-omr/web build:score-view
 *
 * `score-view.html` + `src/scoreView/` are built with the web app's own plugins (React, Tailwind)
 * and stylesheet, then every script, stylesheet and font is inlined — the Bravura @font-face in
 * `base.css` points at `/fonts/Bravura.woff2`, a public file, so it is swapped for a `data:` URI by
 * hand. The result is written to `apps/mobile/src/generated/scoreViewHtml.ts` (gitignored, like any
 * build output): the phone hands it to its WebView as `source={{ html }}`, so the score needs no
 * network and no hosting.
 *
 * ⚠ It is NOT part of `build:app` and never reaches `dist/`: the site does not serve this page.
 * ⚠ Re-run it after any change to the engraver, or the phone keeps drawing with the old one.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(WEB, "dist-score-view");
const TARGET = path.resolve(WEB, "../mobile/src/generated/scoreViewHtml.ts");

await build({
  root: WEB,
  configFile: false,
  plugins: [react(), tailwindcss()],
  base: "./",
  publicDir: false,
  logLevel: "warn",
  build: {
    outDir: OUT_DIR,
    emptyOutDir: true,
    // Everything inline: fonts and images become data: URIs, so the one file is the whole page.
    assetsInlineLimit: () => true,
    cssCodeSplit: false,
    modulePreload: false,
    rollupOptions: {
      input: path.join(WEB, "score-view.html"),
      output: { inlineDynamicImports: true },
    },
  },
});

let html = readFileSync(path.join(OUT_DIR, "score-view.html"), "utf8");
const asset = (rel) => readFileSync(path.join(OUT_DIR, rel.replace(/^\.\//, "")), "utf8");

// The music font from public/, by hand (publicDir is off, so Vite left the URL alone).
const bravura = readFileSync(path.join(WEB, "public/fonts/Bravura.woff2")).toString("base64");
const withFont = (css) => css.replaceAll('url("/fonts/Bravura.woff2")', () => `url("data:font/woff2;base64,${bravura}")`);

html = html.replace(/<link rel="stylesheet"[^>]*href="([^"]+)"[^>]*>/g, (_, href) => `<style>${withFont(asset(href))}</style>`);
html = html.replace(/<script type="module"[^>]*src="([^"]+)"[^>]*><\/script>/g, (_, src) =>
  // `</script` inside the code would end the tag early.
  `<script type="module">${asset(src).replaceAll("</script", "<\\/script")}</script>`,
);
if (/(src|href)="\.\/assets\//.test(html)) throw new Error("an asset was left un-inlined");
if (html.includes('url("/fonts/Bravura.woff2")')) throw new Error("the music font was not inlined");

mkdirSync(path.dirname(TARGET), { recursive: true });
writeFileSync(
  TARGET,
  `// GENERATED by apps/web/tools/build-score-view.mjs — do not edit, re-run it.\n` +
    `export const SCORE_VIEW_HTML: string = ${JSON.stringify(html)};\n`,
);
rmSync(OUT_DIR, { recursive: true, force: true });
console.log(`score view → ${path.relative(path.resolve(WEB, "../.."), TARGET)} (${(html.length / 1024 / 1024).toFixed(2)} MB)`);
